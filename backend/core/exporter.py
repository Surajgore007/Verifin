import os
import re
from typing import Dict, Any, List, Optional
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter
import docx
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

EXPORT_DIR = os.path.join(os.path.dirname(os.path.dirname(__file__)), "exports")
os.makedirs(EXPORT_DIR, exist_ok=True)

def export_xlsx(
    company_name: str,
    metrics: List[Dict[str, Any]],
    verdicts: List[Dict[str, Any]],
    output_filename: str = "verifin_tie_out.xlsx"
) -> str:
    """
    Generates an Excel workbook with live formulas, ratio tables, and audit tie-out ledger.
    """
    wb = openpyxl.Workbook()
    # Sheet 1: Financial Ratios & Tie-Out
    ws1 = wb.active
    ws1.title = "Financial Ratios"
    ws1.views.sheetView[0].showGridLines = True

    # Styling
    header_fill = PatternFill(start_color="1E293B", end_color="1E293B", fill_type="solid")
    header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
    title_font = Font(name="Calibri", size=14, bold=True, color="0F172A")
    regular_font = Font(name="Calibri", size=10)
    bold_font = Font(name="Calibri", size=10, bold=True)
    thin_border = Border(
        left=Side(style='thin', color='CBD5E1'),
        right=Side(style='thin', color='CBD5E1'),
        top=Side(style='thin', color='CBD5E1'),
        bottom=Side(style='thin', color='CBD5E1')
    )

    # Title block
    ws1["A1"] = f"{company_name} - Institutional Financial Tie-Out & Ratios"
    ws1["A1"].font = title_font
    ws1["A2"] = "Generated by Verifin Research Terminal | Decision Support Only, Not Investment Advice"
    ws1["A2"].font = Font(name="Calibri", size=9, italic=True, color="64748B")

    headers1 = ["Metric", "Period", "Calculated Value", "Unit", "Audit Formula", "Input Lineage"]
    for col_idx, h in enumerate(headers1, 1):
        cell = ws1.cell(row=4, column=col_idx, value=h)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="left" if col_idx != 3 else "right")

    row_num = 5
    for m in metrics:
        ws1.cell(row=row_num, column=1, value=m.get("display_name", m.get("name"))).font = regular_font
        ws1.cell(row=row_num, column=2, value=m.get("period", "")).font = regular_font
        
        val_cell = ws1.cell(row=row_num, column=3, value=m.get("value", 0.0))
        val_cell.font = bold_font
        val_cell.number_format = "#,##0.00"
        val_cell.alignment = Alignment(horizontal="right")

        ws1.cell(row=row_num, column=4, value=m.get("unit", "")).font = regular_font
        ws1.cell(row=row_num, column=5, value=m.get("formula_text", "")).font = regular_font
        ws1.cell(row=row_num, column=6, value=str(m.get("input_values", ""))).font = Font(name="Calibri", size=9, color="475569")
        
        for c in range(1, 7):
            ws1.cell(row=row_num, column=c).border = thin_border
        row_num += 1

    # Sheet 2: Audit Tie-Out Ledger
    ws2 = wb.create_sheet(title="Audit Tie-Out Ledger")
    ws2.views.sheetView[0].showGridLines = True

    ws2["A1"] = f"{company_name} - Statement-Level Audit Verification Ledger"
    ws2["A1"].font = title_font

    headers2 = ["Claim ID", "Statement in Draft", "Verdict", "Recomputed Value", "Rationale / Evidence"]
    for col_idx, h in enumerate(headers2, 1):
        cell = ws2.cell(row=3, column=col_idx, value=h)
        cell.fill = header_fill
        cell.font = header_font

    row_num2 = 4
    for v in verdicts:
        ws2.cell(row=row_num2, column=1, value=v.get("claim_id", "")).font = regular_font
        ws2.cell(row=row_num2, column=2, value=v.get("statement", v.get("claim_id", ""))).font = regular_font
        
        verdict_cell = ws2.cell(row=row_num2, column=3, value=v.get("verdict", ""))
        verdict_cell.font = bold_font
        if v.get("verdict") == "Verified":
            verdict_cell.font = Font(name="Calibri", size=10, bold=True, color="059669")
        elif "Conflict" in v.get("verdict", ""):
            verdict_cell.font = Font(name="Calibri", size=10, bold=True, color="DC2626")
        else:
            verdict_cell.font = Font(name="Calibri", size=10, bold=True, color="D97706")

        ws2.cell(row=row_num2, column=4, value=v.get("recomputed_display", "-")).font = regular_font
        ws2.cell(row=row_num2, column=5, value=v.get("rationale", "")).font = regular_font

        for c in range(1, 6):
            ws2.cell(row=row_num2, column=c).border = thin_border
        row_num2 += 1

    # Auto-adjust column widths
    for sheet in [ws1, ws2]:
        for col in sheet.columns:
            max_len = max(len(str(cell.value or '')) for cell in col)
            col_letter = get_column_letter(col[0].column)
            sheet.column_dimensions[col_letter].width = min(max(max_len + 3, 12), 50)

    out_path = os.path.join(EXPORT_DIR, output_filename)
    wb.save(out_path)
    return out_path

def export_docx(
    company_name: str,
    draft_title: str,
    draft_text: str,
    verdicts: List[Dict[str, Any]],
    omissions: List[Dict[str, Any]],
    output_filename: str = "verifin_research_memo.docx"
) -> str:
    """
    Generates an institutional Word research memo with citations and audit tables.
    """
    doc = docx.Document()

    # Header title
    title = doc.add_heading(f"{company_name} - Institutional Financial Review & Tie-Out", level=0)
    title.runs[0].font.color.rgb = RGBColor(15, 23, 42)
    title.runs[0].font.name = "Calibri"

    p_sub = doc.add_paragraph()
    r_sub = p_sub.add_run("Decision Support Only | Not Investment Advice | Generated by Verifin Multi-Agent System")
    r_sub.font.italic = True
    r_sub.font.size = Pt(9)
    r_sub.font.color.rgb = RGBColor(100, 116, 139)

    doc.add_heading("1. Executive Research Memo", level=1)
    for para in draft_text.split("\n\n"):
        if para.strip():
            p = doc.add_paragraph(para.strip())
            p.style.font.name = "Calibri"
            p.style.font.size = Pt(10.5)

    doc.add_heading("2. Statement-Level Tie-Out Ledger", level=1)
    table = doc.add_table(rows=1, cols=4)
    table.style = 'Table Grid'
    hdr_cells = table.rows[0].cells
    hdr_cells[0].text = "Claim ID"
    hdr_cells[1].text = "Verdict"
    hdr_cells[2].text = "Recomputed Figure"
    hdr_cells[3].text = "Audit Provenance"

    for v in verdicts:
        row_cells = table.add_row().cells
        row_cells[0].text = v.get("claim_id", "")
        row_cells[1].text = v.get("verdict", "")
        row_cells[2].text = v.get("recomputed_display") or "-"
        row_cells[3].text = v.get("rationale", "")

    if omissions:
        doc.add_heading("3. Omission Radar (Disclosure Checklist)", level=1)
        om_table = doc.add_table(rows=1, cols=3)
        om_table.style = 'Table Grid'
        om_hdr = om_table.rows[0].cells
        om_hdr[0].text = "Category"
        om_hdr[1].text = "Filing Status"
        om_hdr[2].text = "Disclosure Detail"

        for o in omissions[:8]:
            om_cells = om_table.add_row().cells
            om_cells[0].text = o.get("checklist_title", "")
            om_cells[1].text = o.get("status", "")
            om_cells[2].text = o.get("explanation", "")

    out_path = os.path.join(EXPORT_DIR, output_filename)
    doc.save(out_path)
    return out_path

def export_markdown(
    company_name: str,
    draft_title: str,
    draft_text: str,
    verdicts: List[Dict[str, Any]],
    omissions: List[Dict[str, Any]],
    output_filename: str = "verifin_report.md"
) -> str:
    """
    Generates a clean GitHub Flavored Markdown report with numbered citations.
    """
    lines = [
        f"# {company_name} - Institutional Financial Review & Tie-Out",
        "",
        "> **Notice**: Decision support only. Not investment advice. Recomputed deterministically by Verifin Fact Ledger.",
        "",
        "## 1. Research Memo",
        "",
        draft_text,
        "",
        "## 2. Statement-Level Tie-Out Ledger",
        "",
        "| Claim ID | Verdict | Recomputed Figure | Rationale / Provenance |",
        "| :--- | :--- | :--- | :--- |"
    ]

    for v in verdicts:
        cid = v.get("claim_id", "")
        verd = v.get("verdict", "")
        val = v.get("recomputed_display") or "-"
        rat = v.get("rationale", "").replace("|", "/")
        lines.append(f"| `{cid}` | **{verd}** | `{val}` | {rat} |")

    lines.extend([
        "",
        "## 3. Omission Radar (Disclosure Checklist)",
        "",
        "| Category | Filing Status | Disclosure Detail |",
        "| :--- | :--- | :--- |"
    ])

    for o in omissions:
        title = o.get("checklist_title", "")
        st = o.get("status", "")
        exp = o.get("explanation", "").replace("|", "/")
        lines.append(f"| **{title}** | `{st}` | {exp} |")

    out_path = os.path.join(EXPORT_DIR, output_filename)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    return out_path
